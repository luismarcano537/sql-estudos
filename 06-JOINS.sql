--Liste os pedidos com nome do cliente e do vendedor, primeiro com INNER JOIN e
--depois com LEFT JOIN. Explique quais pedidos desaparecem no INNER e por quê.


SELECT
	O.ORDER_ID AS Pedido,
	C.CUSTOMER_NAME AS Cliente,
	S.SELLER_NAME AS Vendedor,
	ST.STATUS_DESCRIPTION AS Status_Pedido,
	FORMAT(O.ORDER_CREATION_DATE, 'dd/MM/yyyy') AS Fecha_Pedido,
	FORMAT(O.ORDER_UPDATE_DATE, 'dd/MM/yyyy') AS Ultima_atualização
FROM TB_ORDERS AS O
INNER JOIN TB_CUSTOMERS AS C
ON O.ORDER_CUSTOMER_ID = C.CUSTOMER_ID
INNER JOIN TB_SELLERS AS S
ON S.SELLER_ID = O.ORDER_SELLER_ID
INNER JOIN TB_STATUS AS ST
ON ST.STATUS_ID = O.ORDER_STATUS_ID
ORDER BY Fecha_Pedido;


--Liste os clientes que nunca fizeram pedido, usando LEFT JOIN ... WHERE ... IS
--NULL.

SELECT 
	C.CUSTOMER_ID AS ID_Usuário,
	C.CUSTOMER_NAME AS Nome,
	C.CUSTOMER_EMAIL AS Email,
	ISNULL(O.ORDER_ID, 0) AS Pedido
FROM TB_CUSTOMERS AS C
LEFT JOIN TB_ORDERS AS O
ON O.ORDER_CUSTOMER_ID = C.CUSTOMER_ID;

--Liste os produtos nunca vendidos.

SELECT 
	PR.PRODUCT_ID AS Cod_Produto,
	PR.PRODUCT_NAME AS Nome_Produto
FROM TB_PRODUCTS AS PR
LEFT JOIN TB_ORDER_ITENS AS OI
ON OI.PRODUCT_ID = PR.PRODUCT_ID
WHERE OI.PRODUCT_ID IS NULL OR OI.PRODUCT_ID = 0;



--Monte um relatório com pedido, data, cliente, produto, categoria, quantidade e
--subtotal (5 tabelas).

SELECT
	O.ORDER_ID AS Cod_Pedido,
	FORMAT(O.ORDER_CREATION_DATE, 'dd/MM/yyyy') AS Data_pedido,
	C.CUSTOMER_NAME AS Cliente,
	PR.PRODUCT_NAME AS Produto,
	CA.CATEGORY_NAME AS Categoria,
	OI.ORDER_ITEM_QUANTIDADE AS Quantidade,
	OI.ORDER_ITEM_UNIT_VALUE AS Valor_Unit,
	(OI.ORDER_ITEM_QUANTIDADE * OI.ORDER_ITEM_UNIT_VALUE) AS SubTotal
FROM TB_ORDERS AS O
INNER JOIN TB_CUSTOMERS AS C
	ON O.ORDER_CUSTOMER_ID = C.CUSTOMER_ID
INNER JOIN TB_ORDER_ITENS AS OI
	ON OI.ORDER_ID = O.ORDER_ID
INNER JOIN TB_PRODUCTS AS PR
	ON OI.PRODUCT_ID = PR.PRODUCT_ID
INNER JOIN TB_CATEGORIES AS CA
	ON PR.PRODUCT_CATEGORY_ID = CA.CATEGORY_ID


--Calcule o faturamento por categoria e por vendedor, incluindo vendedores sem
--nenhuma venda (valor 0, não NULL)


-- Faturamento por categoria
SELECT
	CA.CATEGORY_NAME AS Categoria,
	SUM(OI.ORDER_ITEM_UNIT_VALUE) AS Faturamento
FROM TB_ORDERS AS O
INNER JOIN TB_ORDER_ITENS AS OI
ON OI.ORDER_ID = O.ORDER_ID
INNER JOIN TB_PRODUCTS AS PR
ON OI.PRODUCT_ID = PR.PRODUCT_ID
INNER JOIN TB_CATEGORIES AS CA
ON PR.PRODUCT_CATEGORY_ID = CA.CATEGORY_ID
GROUP BY CA.CATEGORY_NAME
HAVING SUM(OI.ORDER_ITEM_UNIT_VALUE) > 0
ORDER BY Faturamento DESC;

-- Faturamento por vendedor

SELECT
	SE.SELLER_NAME AS Vendedor,
	SUM(OI.ORDER_ITEM_UNIT_VALUE) AS Faturamento
FROM TB_ORDERS AS O
INNER JOIN TB_ORDER_ITENS AS OI
ON OI.ORDER_ID = O.ORDER_ID
INNER JOIN TB_PRODUCTS AS PR
ON OI.PRODUCT_ID = PR.PRODUCT_ID
INNER JOIN TB_SELLERS AS SE
ON O.ORDER_SELLER_ID = SE.SELLER_ID
GROUP BY SE.SELLER_NAME
HAVING SUM(OI.ORDER_ITEM_UNIT_VALUE) > 0
ORDER BY Faturamento DESC;

--Monte uma lista de contatos (clientes e vendedores) com uma coluna Tipo, usando
--UNION e depois UNION ALL. Compare as contagens e explique a diferença.

SELECT
	CUSTOMER_NAME AS CONTATO,
	'Cliente' AS TIPO
FROM TB_CUSTOMERS
UNION ALL
SELECT
	SELLER_NAME AS CONTATO,
	'Vendedor' AS TIPO
FROM TB_SELLERS;

--Liste os 3 clientes com maior faturamento total, com nome e valor.

SELECT TOP (3)
	C.CUSTOMER_ID AS Cod_Cliente,
	C.CUSTOMER_NAME AS Cliente,
	SUM(OI.ORDER_ITEM_QUANTIDADE * OI.ORDER_ITEM_UNIT_VALUE) AS Faturamento_total
FROM TB_ORDERS AS O
INNER JOIN TB_ORDER_ITENS AS OI
ON OI.ORDER_ID = O.ORDER_ID
INNER JOIN TB_CUSTOMERS AS C
ON O.ORDER_CUSTOMER_ID = C.CUSTOMER_ID
GROUP BY C.CUSTOMER_ID, C.CUSTOMER_NAME
ORDER BY Faturamento_total DESC;
